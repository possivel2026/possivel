create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  candidate text;
begin
  candidate := lower(regexp_replace(coalesce(new.raw_user_meta_data ->> 'handle', ''), '[^a-zA-Z0-9_]', '', 'g'));
  if candidate = '' then
    candidate := 'usuario_' || substr(new.id::text, 1, 8);
  end if;
  if exists(select 1 from public.profiles where handle = candidate) then
    candidate := left(candidate, 22) || '_' || substr(new.id::text, 1, 6);
  end if;

  insert into public.profiles (id, name, handle)
  values (
    new.id,
    left(coalesce(nullif(trim(new.raw_user_meta_data ->> 'name'), ''), 'Pessoa possível'), 80),
    candidate
  )
  on conflict (id) do nothing;
  return new;
end;
$$;


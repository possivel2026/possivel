create or replace function public.notify_comment()
returns trigger language plpgsql security definer set search_path=public as $$
declare owner_id uuid; actor_name text;
begin
  select author_id into owner_id from public.posts where id=new.post_id;
  if owner_id is null or owner_id=new.author_id then return new; end if;
  select name into actor_name from public.profiles where id=new.author_id;
  insert into public.notifications(user_id,actor_id,type,title,body,link)
  values(owner_id,new.author_id,'comment','Novo comentário',coalesce(actor_name,'Alguém') || ' comentou sua publicação.','#inicio');
  return new;
end $$;


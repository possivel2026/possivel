create or replace function public.update_cause_totals()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.cause_id is not null and new.status = 'paid' and (tg_op = 'INSERT' or old.status is distinct from 'paid') then
    update public.causes
    set raised_amount = raised_amount + new.amount,
        support_count = support_count + 1
    where id = new.cause_id;
  elsif tg_op = 'UPDATE' and old.cause_id is not null and old.status = 'paid' and new.status in ('refunded','failed') then
    update public.causes
    set raised_amount = greatest(0, raised_amount - old.amount),
        support_count = greatest(0, support_count - 1)
    where id = old.cause_id;
  end if;
  return new;
end;
$$;

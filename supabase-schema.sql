create or replace function public.get_effective_plan(p_user_id uuid default auth.uid())
returns text
language sql
stable
security definer
set search_path = public
as $$
  select coalesce((
    select plan from public.subscriptions
    where user_id = coalesce(p_user_id, auth.uid())
      and status in ('active','grace_period')
      and (current_period_end is null or current_period_end > now())
    order by created_at desc
    limit 1
  ), 'free');
$$;

create or replace function public.can_use_feature(p_user_id uuid, p_feature_key text)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select coalesce((select enabled from public.plan_entitlements
    where plan = public.get_effective_plan(p_user_id) and feature_key = p_feature_key), false);
$$;

create or replace function public.get_user_entitlements(p_user_id uuid default auth.uid())
returns table(feature_key text, enabled boolean, numeric_limit numeric)
language sql
stable
security definer
set search_path = public
as $$
  select pe.feature_key, pe.enabled, pe.numeric_limit
  from public.plan_entitlements pe
  where pe.plan = public.get_effective_plan(coalesce(p_user_id, auth.uid()));
$$;

create or replace function public.check_plan_limit(p_user_id uuid, p_feature_key text)
returns boolean
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_limit numeric;
  v_usage numeric;
begin
  select numeric_limit into v_limit
  from public.plan_entitlements
  where plan = public.get_effective_plan(p_user_id) and feature_key = p_feature_key;
  if v_limit is null then return public.can_use_feature(p_user_id, p_feature_key); end if;
  if p_feature_key = 'active_listings' then
    select count(*) into v_usage from public.listings where seller_id = p_user_id and status = 'active';
  else
    select coalesce(sum(usage),0) into v_usage from public.usage_counters where user_id = p_user_id and feature_key = p_feature_key;
  end if;
  return v_usage < v_limit;
end;
$$;


  insert into public.notifications(user_id,actor_id,type,title,body,link)
  values(new.receiver_id,new.sender_id,'message','Nova mensagem',coalesce(actor_name,'Alguém') || ' enviou uma mensagem.','#messages');
  return new;
end $$;

